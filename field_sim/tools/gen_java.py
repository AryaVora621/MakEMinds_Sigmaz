"""Generate docs/FieldConstants_from_CAD.java.txt from data/field_model/field_constants.json"""
import json, os
B = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
fc = json.load(open(os.path.join(B, 'data', 'field_model', 'field_constants.json')))
def arr(v): return '{' + ', '.join('%.3f' % (round(x, 3) + 0.0) for x in v) + '}'
L = []
a = L.append
a('// Generated by field_sim/tools/gen_java.py from field_constants.json (Onshape field CAD). Units: inches, PEDRO frame')
a('// (origin audience-left corner, +x audience right, +y far wall, +z up). Red hive at low x. Provenance: see FIELD_CONSTANTS.md.')
a('public final class FieldConstantsCad {')
a('    private FieldConstantsCad() {}')
a('    public static final double FIELD_NOMINAL = 144.0;            // OFFICIAL 9.2 (approx)')
w = fc['field']['walls']['glass_inner_faces']
a('    public static final double WALL_X_LO = %.2f, WALL_X_HI = %.2f, WALL_Y_LO = %.2f, WALL_Y_HI = %.2f; // DERIVED-FROM-CAD glass inner faces (interior %.2f in, NOT 144)' % (w['x_low'], w['x_high'], w['y_low'], w['y_high'], fc['field']['walls']['interior_size_cad'][0]))
a('    public static final double TILE_TOP_Z = 0.0, PIVOT_Z = 43.95;   // PIVOT_Z OFFICIAL 9.6.1 and CAD')
a('    public static final double TIP_ANGLE_DEG = 30.0;                  // DERIVED-FROM-CAD, OFFICIAL Fig 9-10 callout')
a('    public static final double TAG_SIZE = 3.25;                       // OFFICIAL 9.9')
a('    public static final double PIVOT_Y = 72.0;')
a('    public static final double RED_PIVOT_X = %.3f, BLUE_PIVOT_X = %.3f;   // DERIVED-FROM-CAD (official Fig 9-10: 59.25 / 84.75)' % (fc['hives']['red']['pivot'][0], fc['hives']['blue']['pivot'][0]))
a('')
a('    // ---- hive aim points: index [hive 0=red 1=blue][state 0=AUDIENCE_UP 1=FAR_UP] = centroid of the UP cell opening (x, y, z)')
a('    // Opening is a pentagon 20.04 w x 14.0 tall (in plane); normal points outward, 30 deg above horizontal.')
def hv(h, st, key, cell):
    return fc['hives'][h]['states'][st]['cells'][cell][key]
a('    public static final double[][][] AIM = {')
for h in ('red', 'blue'):
    a('        { %s, %s },' % (arr(hv(h, 'audience_up', 'aim_point', 'audience')), arr(hv(h, 'far_up', 'aim_point', 'far'))))
a('    };')
a('    public static final double[][][] AIM_BBOX_CENTER = {   // centre of the 20 x 14 bounding rectangle of the opening (higher than centroid)')
for h in ('red', 'blue'):
    a('        { %s, %s },' % (arr(hv(h, 'audience_up', 'aim_point_bbox_center', 'audience')), arr(hv(h, 'far_up', 'aim_point_bbox_center', 'far'))))
a('    };')
a('    public static final double[][][] OPENING_NORMAL = {    // outward unit normal of the UP cell opening')
for h in ('red', 'blue'):
    a('        { %s, %s },' % (arr(hv(h, 'audience_up', 'opening_normal', 'audience')), arr(hv(h, 'far_up', 'opening_normal', 'far'))))
a('    };')
a('    /** Opening corners of the UP cell [hive][state][corner BL,BR,TR,TL seen from outside][xyz]. */')
a('    public static final double[][][][] OPENING_CORNERS = {')
for h in ('red', 'blue'):
    a('        { { %s }, { %s } },' % (', '.join(arr(p) for p in hv(h, 'audience_up', 'opening_corners', 'audience')), ', '.join(arr(p) for p in hv(h, 'far_up', 'opening_corners', 'far'))))
a('    };')
a('    /** Floor (inside of bottom skin) corners of the UP cell: front-left, front-right, back-right, back-left. */')
a('    public static final double[][][][] FLOOR_CORNERS = {')
for h in ('red', 'blue'):
    a('        { { %s }, { %s } },' % (', '.join(arr(p) for p in hv(h, 'audience_up', 'floor_corners', 'audience')), ', '.join(arr(p) for p in hv(h, 'far_up', 'floor_corners', 'far'))))
a('    };')
a('    public static final double CELL_DEPTH = %.3f;   // DERIVED-FROM-CAD (OFFICIAL 12.04)' % hv('red', 'audience_up', 'depth', 'audience'))
a('')
a('    // ---- AprilTags 30..45: index [id-30][state 0=AUDIENCE_UP 1=FAR_UP] ; tag centre, outward normal (toward viewer), up, right as seen facing the tag')
for key in ('center', 'normal', 'up', 'right'):
    a('    public static final double[][][] TAG_%s = {' % key.upper())
    for tid in range(30, 46):
        t = fc['apriltags'][str(tid)]['states']
        a('        { %s, %s }, // id %d %s %s' % (arr(t['audience_up'][key]), arr(t['far_up'][key]), tid, fc['apriltags'][str(tid)]['alliance'], fc['apriltags'][str(tid)]['side']))
    a('    };')
a('')
a('    // ---- flowers: opening centre (x, y, z of top ring), id order 1..4. No fixed owner alliance (ownership is dynamic, manual 10.5.2).')
a('    public static final double[][] FLOWER_OPENING = {')
for f in fc['flowers']:
    a('        %s, // flower %d (%s wall)' % (arr(f['opening_center']), f['id'], f['wall']))
a('    };')
a('    public static final double FLOWER_RADIUS = %.2f, FLOWER_OPENING_Z = %.2f, FLOWER_SCORING_Z_LO = %.2f, FLOWER_SCORING_Z_HI = %.2f, FLOWER_BACKSTOP_TOP_Z = %.2f;' % (fc['flowers'][0]['radius'], fc['flowers'][0]['opening_height'], fc['flowers'][0]['scoring_volume_z'][0], fc['flowers'][0]['scoring_volume_z'][1], fc['flowers'][0]['backstop_top_z']))
a('')
a('    // ---- zones {xmin, ymin, xmax, ymax}, outer edges of the tape (DERIVED-FROM-CAD tape placement; sizes agree with manual 9.3)')
for k, z in fc['zones'].items():
    a('    public static final double[] %s = {%.2f, %.2f, %.2f, %.2f};' % (k.upper(), z['xmin'], z['ymin'], z['xmax'], z['ymax']))
a('')
b = fc['balls']
a('    public static final double POLLEN_DIAMETER = %.2f, NECTAR_DIAMETER = %.2f; // DERIVED-FROM-CAD' % (b['pollen']['diameter'], b['nectar_red']['diameter']))
a('}')
open(os.path.join(B, 'docs', 'FieldConstants_from_CAD.java.txt'), 'w').write('\n'.join(L) + '\n')
print(len(L))
